const dictionaries: Record<Locale, StudioMessages> = { pt, en, es };

export const studioMessages = (locale: Locale): StudioMessages => dictionaries[locale];

/** "{title} (copy)" + { title: "API" } → "API (copy)". Unknown placeholders stay as they are. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}
